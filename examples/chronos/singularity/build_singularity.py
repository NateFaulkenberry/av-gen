#!/usr/bin/env python3
"""Writes CHRONOS, Temporal Singularity's layers, scene and projects (docs/prototypes/chronos/20-24).

    python3 examples/chronos/singularity/build_singularity.py

1. The layers. singularity.wgsl (Background) and lens.wgsl (Late, ADR-1935) are generated from *.src.wgsl with
   field.wgsl spliced in, so the one field cannot drift between them. field.py mirrors the field for step 2.
2. The figures. Eight MPFB figures (build_souls.py, CC0) are integrated through the field (field.py): pulled toward
   the wandering main mass, dragged round it, deflected and slung by the eddies, slowed by a little drag so they
   spiral in, consumed at the core and reborn at the edge of the frame. Their positions, orientations and scales are
   timeline keys (scrub-safe), on a plane 26-34 m in front of a fixed camera, so screen and field agree.
3. Their temporal transformation (ADR-1934/1936). Each figure is a slot; its stage is a function of its depth in the
   field: intact far out, echoes, the stretch with its colours drifting apart, fracture along its own direction of
   travel, then squeezed to a ribbon and gone at the core. Eddies tear at figures that pass near them, too.
4. The projects:
     singularity.json     Test A (the singularity alone)
     singularity-b.json   Test B: the figures in the field, no temporal transformation, no lensing
     singularity-c.json   Test C: B + the temporal transformation
     singularity-d.json   Test D: C + the gravitational distortion of everything (the full S1 composition)

Audio by relative path (never committed). The figure GLBs are built into assets/chronos/build/souls/ (gitignored).
Out of examples/index.json.
"""
import json
import math
import os
import random

import field as F

HERE = os.path.dirname(os.path.abspath(__file__))
DURATION = 48.0       # seconds of keys
DT = 0.2              # key spacing
SIM_DT = 1.0 / 60.0
N = 10
CAM_Z = 30.0
TAN = math.tan(math.radians(20.0))   # fov 40
GM0 = 0.012           # the main mass, in frame heights^3 / s^2
GME = 0.006           # each eddy at full presence
SWIRL = 0.018         # the tangential drag of the main mass (clockwise)
DRAG = 0.045          # per second, so orbits decay into spirals


# ---- 1. the layers ------------------------------------------------------------------------------------------------

def layers():
    fld = open(os.path.join(HERE, "field.wgsl")).read()
    for name in ("singularity", "lens"):
        src = open(os.path.join(HERE, f"{name}.src.wgsl")).read()
        assert "//@FIELD" in src
        out = src.replace("//@FIELD", fld)
        out = out.replace("*/\n", "*/\n\n// GENERATED by build_singularity.py from " + name + ".src.wgsl and field.wgsl: edit those.\n", 1)
        with open(os.path.join(HERE, f"{name}.wgsl"), "w") as f:
            f.write(out)


# ---- 2. the figures -----------------------------------------------------------------------------------------------

def accel(x, v, t):
    c0 = F.main_center(t)
    R0 = F.core_radius_at(t)
    ax = ay = 0.0
    dx, dy = c0[0] - x[0], c0[1] - x[1]
    r2 = dx * dx + dy * dy + R0 * R0
    r = math.sqrt(r2)
    ax += GM0 * dx / (r2 * r)
    ay += GM0 * dy / (r2 * r)
    # frame dragging: a clockwise tangential pull, strongest near the mass and in a tear
    sw = SWIRL * (1.0 + 1.5 * F.tear(t)) / r2 * r
    ax += sw * dy / r
    ay += -sw * dx / r
    for i in range(3):
        c, er, spin, w = F.eddy(i, t, c0, R0)
        ex, ey = c[0] - x[0], c[1] - x[1]
        e2 = ex * ex + ey * ey + (2 * er) ** 2
        e = math.sqrt(e2)
        ax += GME * w * ex / (e2 * e)
        ay += GME * w * ey / (e2 * e)
        s = 0.004 * w * spin / e2 * e
        ax += -s * ey / e
        ay += s * ex / e
    ax -= DRAG * v[0]
    ay -= DRAG * v[1]
    return ax, ay


def spawn(rng, t):
    """Reborn just inside the frame's edge (so it is seen), in a near-circular orbit with a little fall."""
    c0 = F.main_center(t)
    edge = rng.choice(("l", "r", "t", "b"))
    u = rng.uniform(-1.0, 1.0)
    ps = {"l": (-0.82, 0.42 * u), "r": (0.82, 0.42 * u), "t": (0.8 * u, 0.44), "b": (0.8 * u, -0.44)}[edge]
    x = F.screen_to_field(ps, t)
    dx, dy = x[0] - c0[0], x[1] - c0[1]
    d = math.hypot(dx, dy)
    vt = math.sqrt(GM0 / d) * rng.uniform(0.75, 1.05)
    vr = rng.uniform(0.0, 0.03)
    v = (vt * dy / d - vr * dx / d, -vt * dx / d - vr * dy / d)   # clockwise, and a little inward
    return x, v


def to_world(p_screen, depth):
    h = 2.0 * depth * TAN
    return (p_screen[0] * h, p_screen[1] * h, CAM_Z - depth)


def stage(xr, near_eddy):
    """Slot parameters for a figure xr core radii from the main mass (and how near an eddy it is)."""
    b = max(F.smoothstep(9.0, 6.0, xr), 0.6 * near_eddy)
    c = F.smoothstep(6.0, 3.5, xr)
    d = max(F.smoothstep(3.6, 2.0, xr), 0.5 * near_eddy)
    trail = 9.0 * b + 16.0 * c
    echo = (7.0 * b * (1.0 - c) + 1.0 * c) if b > 1e-3 else 0.0
    fade = 0.7 - 0.25 * c
    fracture = 0.25 * d
    rgb = 2.0 * c + 3.5 * d
    return trail, echo, fade, fracture, rgb


def figure_tracks(index):
    rng = random.Random(1935 + 17 * index)
    slot = index + 1
    name = f"figure{slot}"
    size = rng.uniform(1.6, 2.3)
    depth = rng.uniform(26.0, 34.0)
    head_first = rng.random() < 0.6
    tumble = rng.uniform(-0.6, 0.6)
    roll0 = rng.uniform(-40, 40)
    tilt0 = rng.uniform(-25, 25)
    t = -rng.uniform(0.0, 10.0)          # a pre-roll, so the frame opens mid-flight
    x, v = spawn(rng, t)
    hidden_until = -1e9
    off_since = None
    keys = {k: [] for k in ("pos", "rot", "scl", "trail", "echo", "fade", "frac", "rgb", "angle")}
    next_key = 0.0
    prev_rot = None
    while t <= DURATION + 1e-6:
        R0 = F.core_radius_at(t)
        c0 = F.main_center(t)
        hidden = t < hidden_until
        if not hidden:
            ax, ay = accel(x, v, t)
            v = (v[0] + ax * SIM_DT, v[1] + ay * SIM_DT)
            x = (x[0] + v[0] * SIM_DT, x[1] + v[1] * SIM_DT)
            r = math.hypot(x[0] - c0[0], x[1] - c0[1])
            ps_now = F.field_to_screen(x, t)
            off = abs(ps_now[0]) > 1.0 or abs(ps_now[1]) > 0.62
            off_since = (off_since if off_since is not None else t) if off else None
            if r < 1.15 * R0 or (off_since is not None and t - off_since > 1.5):
                # consumed (or flung out of the frame): gone, and reborn at the edge after a breath
                hidden_until = t + rng.uniform(1.0, 3.5)
                x, v = spawn(rng, hidden_until)
                depth = rng.uniform(26.0, 34.0)
                off_since = None
                hidden = True
        if t >= next_key - 1e-9 and t >= -1e-9:
            r = math.hypot(x[0] - c0[0], x[1] - c0[1])
            xr = r / R0
            near = 0.0
            for i in range(3):
                c, er, spin, w = F.eddy(i, t, c0, R0)
                near = max(near, w * F.smoothstep(6.0 * er, 2.0 * er, math.hypot(x[0] - c[0], x[1] - c[1])))
            ps = F.field_to_screen(x, t)
            ps2 = F.field_to_screen((x[0] + v[0] * 0.05, x[1] + v[1] * 0.05), t + 0.05)
            vs = ((ps2[0] - ps[0]) / 0.05, (ps2[1] - ps[1]) / 0.05)
            speed = math.hypot(*vs)
            world = to_world(ps, depth)
            # orientation: the body along its flight when it is fast, tumbling when it is slow
            fly = math.degrees(math.atan2(vs[1], vs[0])) - (90.0 if head_first else -90.0)
            align = F.smoothstep(0.08, 0.3, speed)
            spinz = fly + (1.0 - align) * math.degrees(tumble * t)
            rotv = [tilt0 + 15.0 * math.sin(0.3 * t + index), roll0 + math.degrees(0.4 * tumble * t), spinz]
            if prev_rot is not None:
                rotv = [c + 360.0 * round((p - c) / 360.0) for p, c in zip(prev_rot, rotv)]
            prev_rot = rotv
            e = F.smoothstep(2.2, 1.25, xr)
            # it shrinks continuously over its last approach, so it is swallowed, not switched off
            s = 0.0 if hidden else size * F.smoothstep(1.15, 1.75, xr)
            w = s * (1.0 - 0.75 * e)
            length = s * (1.0 + 0.8 * e)
            tr, ec, fa, fr, rg = stage(xr, near) if not hidden else (0.0, 0.0, 0.7, 0.0, 0.0)
            ang = math.degrees(math.atan2(-vs[1], vs[0]))   # uv: x right, y down
            kt = round(next_key, 3)
            keys["pos"].append((kt, [round(c, 3) for c in world]))
            keys["rot"].append((kt, [round(c, 2) for c in rotv]))
            keys["scl"].append((kt, [round(max(w, 0.001), 4), round(max(length, 0.001), 4), round(max(w, 0.001), 4)]))
            keys["trail"].append((kt, round(tr, 2)))
            keys["echo"].append((kt, round(ec, 2)))
            keys["fade"].append((kt, round(fa, 3)))
            keys["frac"].append((kt, round(fr, 3)))
            keys["rgb"].append((kt, round(rg, 2)))
            keys["angle"].append((kt, round(ang, 1)))
            next_key += DT
        t += SIM_DT
    return name, slot, keys


def track(target, keys, interp="linear"):
    return {"target": target, "component": -1, "enabled": True, "timeBase": "seconds", "mode": "replace",
            "loopLength": 0.0, "keys": [{"time": t, "value": v, "interp": interp} for t, v in keys]}


def core_light_track():
    keys = []
    t = 0.0
    while t <= DURATION + 1e-6:
        ps = F.field_to_screen(F.main_center(t), t)
        w = to_world(ps, 30.0)
        keys.append((round(t, 3), [round(w[0], 3), round(w[1], 3), round(w[2] + 1.5, 3)]))
        t += 0.5
    return track("lights/core/position", keys)


# ---- 3. the scene and the projects ----------------------------------------------------------------------------------

def scene(with_figures):
    nodes = []
    if with_figures:
        for i in range(N):
            nodes.append({"name": f"figure{i + 1}", "kind": "gltf",
                          "asset": f"../../../assets/chronos/build/souls/soul-{i % 8 + 1}.glb",
                          "position": [0.0, 0.0, -50.0], "rotation": [0.0, 0.0, 0.0], "scale": [1.0, 1.0, 1.0],
                          "temporalSlot": i + 1})
    return {
        "format": "avgen-scene", "version": 1, "name": "chronos-singularity",
        "_note": "CHRONOS, Temporal Singularity (docs/prototypes/chronos/20-24): written by build_singularity.py. The "
                 "singularity is the background layer singularity.wgsl; the lensing is the late layer lens.wgsl.",
        "camera": {"mode": 1, "position": [0.0, 0.0, CAM_Z], "target": [0.0, 0.0, 0.0], "fov": 40.0, "near": 0.5,
                   "far": 2000.0},
        "environment": {"background": [0.0, 0.0, 0.0], "intensity": 0.0, "skyIntensity": 0.0,
                        "lightFromEnvironment": False, "fallbackAmbient": False, "volumeDensity": 0.0,
                        "ambientOcclusion": False, "contactShadows": False,
                        "sky": {"enabled": False, "background": False}},
        # the singularity's light rides the core: hot amber from wherever it is; a dim violet fill from the camera side
        "lights": [
            {"id": "core", "name": "core", "type": "point", "role": "key", "position": [0.0, 0.0, 4.0],
             "color": [1.0, 0.55, 0.22], "intensity": 3800.0, "range": 120.0, "castsShadow": False},
            {"id": "fill", "name": "fill", "type": "directional", "role": "fill", "direction": [0.2, -0.3, -1.0],
             "color": [0.45, 0.25, 0.75], "intensity": 0.6, "castsShadow": False},
        ] if with_figures else [],
        "nodes": nodes,
    }


BASE_PARAMS = {
    "camera/exposure/mode": 0,
    "camera/exposure/compensation": -0.3,
    "post/bloom/enabled": True,
    "post/bloom/intensity": 0.32,
    "post/bloom/threshold": 1.1,
    "post/tonemap/chroma-retention": 0.65,
    "post/output/vignette": 0.18,
    "post/output/grain": 0.03,
    "post/grade/contrast": 1.06,
    "post/grade/saturation": 1.08,
    "temporal/echo/enabled": False,
    "temporal/mosh/enabled": False,
}


def project(kind, figure_data):
    scene_file = "singularity.scene.json" if kind == "a" else "singularity-figures.scene.json"
    shaders = [{"path": "singularity.wgsl", "stage": "background"}]
    params = dict(BASE_PARAMS)
    tracks = []
    if kind in ("b", "c", "d"):
        tracks.append(core_light_track())
        for name, slot, keys in figure_data:
            tracks += [track(f"nodes/{name}/position", keys["pos"]), track(f"nodes/{name}/rotation", keys["rot"]),
                       track(f"nodes/{name}/scale", keys["scl"])]
    if kind in ("c", "d"):
        params.update({"temporal/slit/enabled": True, "temporal/slit/amount": 1.0, "temporal/slit/span": 60.0,
                       "temporal/slit/gate": 1.0, "temporal/history/capacity": 64.0, "temporal/history/stride": 1.0})
        for name, slot, keys in figure_data:
            sl = f"temporal/slit/slot{slot}/"
            params[sl + "strips"] = 26.0
            tracks += [track(sl + "trail", keys["trail"]), track(sl + "echo", keys["echo"]),
                       track(sl + "fade", keys["fade"]), track(sl + "fracture", keys["frac"]),
                       track(sl + "rgb", keys["rgb"]), track(sl + "angle", keys["angle"])]
    if kind in ("c", "d"):
        # Test C has the lens layer too, with its warp at zero: only its palette guard acts
        shaders.append({"path": "lens.wgsl", "stage": "late"})
    if kind == "c":
        params.update({"shader/lens/lens": 0.0, "shader/lens/drag": 0.0, "shader/lens/shear": 0.0})
    return {
        "format": "avgen-project", "version": 4, "app": {"name": "CHRONOS - Temporal Singularity"},
        "assets": {"scene": {"kind": "composition", "path": scene_file},
                   "audio": "../../../assets/audio/feline-footwear.wav",
                   "stems": [{"key": "drums", "label": "Drums", "role": "drums",
                              "file": "../../../assets/audio/stems/feline-footwear (Drums).wav"}]},
        "feeds": {"beat": "stem.drums"},
        "shaders": shaders,
        "parameters": params,
        "sources": [], "routes": [],
        "timeline": {"enabled": True, "cues": [], "tracks": tracks},
        "render": {"width": 1920, "height": 1080, "fps": 30, "output": "video",
                   "path": f"renders/singularity-{kind}.mp4"},
    }


if __name__ == "__main__":
    layers()
    figure_data = [figure_tracks(i) for i in range(N)]
    with open(os.path.join(HERE, "singularity.scene.json"), "w") as f:
        json.dump(scene(False), f, indent=1)
    with open(os.path.join(HERE, "singularity-figures.scene.json"), "w") as f:
        json.dump(scene(True), f, indent=1)
    for kind in ("a", "b", "c", "d"):
        name = "singularity.json" if kind == "a" else f"singularity-{kind}.json"
        with open(os.path.join(HERE, name), "w") as f:
            json.dump(project(kind, figure_data), f, separators=(",", ":"))
    print("wrote singularity.wgsl, lens.wgsl, the scenes and projects a-d")
