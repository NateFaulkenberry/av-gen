"""Hero-asset proofs: write isolated AV Gen test compositions (one asset, a fire, a moon, a sand disc) into
docs/prototypes/strange-attractor/hero/. Never the real Strange Attractor scene.

    python3 examples/strange-attractor/hero/proof_scene.py <name> <asset.glb relative to the repo> [scale] [anim] [wide|close]
    tools/gpu-lock.sh build/release/src/avgen --headless \
        --composition docs/prototypes/strange-attractor/hero/<name>.scene.json \
        --render <dir> --range 4:4.016 --fps 60 --size 1280x720

The light is the night camp's in miniature: a warm point fire 1.6 m in front and to the side of the subject (the
scene's campfire colour, flicker off so stills compare), the stone pit and the scene's flame particles at it, a cool
moon from behind as a rim with shadows, a little sky ambient. AgX tone mapping (48-night-lighting-research.md A1).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
OUT = os.path.join(REPO, "docs", "prototypes", "strange-attractor", "hero")
REL = os.path.relpath(REPO, OUT)

name, asset = sys.argv[1], sys.argv[2]
scale = float(sys.argv[3]) if len(sys.argv) > 3 else 1.0
anim = sys.argv[4] if len(sys.argv) > 4 else ""
shot = sys.argv[5] if len(sys.argv) > 5 else "wide"   # wide | close
fire = [0.9, 0.0, 1.6]
node = {"name": "subject", "kind": "gltf", "asset": f"{REL}/{asset}", "position": [0, 0, 0], "rotation": [0, 0, 0],
        "scale": [scale] * 3}
if anim:
    node["animation"] = {"state": anim, "speed": 1.0}
scene = {
    "format": "avgen-scene", "version": 1, "name": f"Hero proof: {name}",
    "_note": "Generated by examples/strange-attractor/hero/proof_scene.py; an isolated asset proof, not the scene.",
    "camera": ({"mode": 1, "position": [-0.6, 1.5, 6.2], "target": [0.15, 1.15, 0], "fov": 34, "orbitSpeed": 0} if shot == "wide"
               else {"mode": 1, "position": [-0.5, 1.9, 3.3], "target": [0.05, 1.55, 0], "fov": 34, "orbitSpeed": 0}),
    "environment": {"background": [0.004, 0.006, 0.016], "intensity": 0.035, "volumeDensity": 0.0,
                    "sky": {"enabled": False, "background": False}, "shadowRange": 40.0, "shadowCascades": 4,
                    "contactShadows": True, "ambientOcclusion": True},
    "post": {"tonemap": 1, "bloomIntensity": 0.04},
    "lights": [
        {"name": "fire", "type": "point", "position": [fire[0], 0.95, fire[2]], "color": [1.0, 0.52, 0.22],
         "intensity": 30.0, "range": 18.0, "castsShadow": True, "shadowStrength": 1.0, "flicker": 0.0},
        {"name": "moon", "type": "directional", "direction": [-0.35, -0.5, -0.8], "color": [0.62, 0.72, 1.0],
         "intensity": 0.5, "castsShadow": True, "shadowStrength": 1.0},
    ],
    "nodes": [
        {"name": "ground", "kind": "gltf", "asset": f"{REL}/assets/strange-attractor/hero/stage-ground.glb",
         "position": [0, 0, 0], "scale": [1, 1, 1]},
        {"name": "pit", "kind": "gltf", "asset": f"{REL}/assets/strange-attractor/build/ph-stone_fire_pit.glb",
         "position": fire, "rotation": [0, 20, 0], "scale": [0.85, 0.85, 0.85]},
        node,
    ],
}
# the scene's flame and core particles, moved to the test fire
src = json.load(open(os.path.join(REPO, "examples", "strange-attractor", "strange-attractor-flythrough.scene.json")))
for n in src["nodes"]:
    if n.get("name") in ("campfire-flames", "campfire-core", "campfire-embers"):
        n = json.loads(json.dumps(n))
        p = n["particles"]["position"]
        n["particles"]["position"] = [fire[0], p[1] - 1.68 + 0.0, fire[2]]
        n["visible"] = True
        scene["nodes"].append(n)
os.makedirs(OUT, exist_ok=True)
path = os.path.join(OUT, f"{name}.scene.json")
json.dump(scene, open(path, "w"), indent=1)
print(path)
