def generate_meshes():
    """Write the land's GLBs (and their twins) into examples/sonic-abstract/meshes/. Deterministic."""
    out = {}
    for name, r0, r1, nr, nth, base, amp, wl, seed, peak, _col in RANGES:
        tris = mx.polar_range(r0, r1, nr, nth, range_height(r0, r1, base, amp, wl, seed, peak), seed=seed)
        out[name] = tris
    isl = []
    for seed, rad, hgt, sides, rings, pos, lean in ISLAND:
        isl += mx.translate(mx.rock(seed, rad, hgt, sides, rings, sink=6.0, lean=lean), pos)
    out["island"] = isl
    rk = []
    for seed, rad, hgt, sides, rings, ang, dist in ROCKS:
        rk += mx.translate(mx.rock(seed, rad, hgt, sides, rings, sink=3.0), (dist * math.sin(ang), 0.0,
                                                                            dist * math.cos(ang)))
    out["rocks"] = rk
    for name, tris in list(out.items()):
        out[name] = tris = mx.clip_above(tris, 0.0)
        mx.write_faceted(os.path.join(MESH_DIR, "da-%s.glb" % name), tris, name)
        mx.write_faceted(os.path.join(MESH_DIR, "da-%s-twin.glb" % name), mx.mirrored(tris), name + "Twin")
    return list(out)


