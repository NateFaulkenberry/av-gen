def crest(r, r0, r1, peak=0.45):
    """A range's profile across its band: 0 at both edges (under water), 1 at the crest. It leaves the water steeply
    (a shallow shore draws as a pale flat beach)."""
    t = (r - r0) / (r1 - r0)
    if t <= 0.0 or t >= 1.0:
        return 0.0
    if t < peak:
        return mx.smooth(0.0, peak, t) ** 0.45
    return mx.smooth(1.0, peak, t) ** 0.7


def range_height(r0, r1, base, amp, wl, seed, peak=0.45, sink=14.0):
    def h(x, z, r, th):
        c = crest(r, r0, r1, peak)
        n = mx.fbm(x / wl, z / wl, seed, 4, ridged=True)
        return c * (base + amp * n) - sink * (1.0 - c) ** 2 - 4.0
    return h


