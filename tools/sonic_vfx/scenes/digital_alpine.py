def camera_track(s):
    """A low glide round the lake: the circle of radius CAM_R. The view swings slowly (twice a circuit) between
    looking ahead along the glide (the far ranges coming) and looking in across the water at the island with the
    ranges sliding past behind it."""
    kp, kt = [], []
    steps = 64
    for i in range(steps + 1):
        u = i / steps
        th = THETA0 + 2.0 * math.pi * u
        pos = (CAM_R * math.sin(th), CAM_H + 2.5 * math.sin(4.0 * math.pi * u), CAM_R * math.cos(th))
        fwd = (math.cos(th), 0.0, -math.sin(th))            # d/dtheta of the position: counter-clockwise from above
        inward = (-math.sin(th), 0.0, -math.cos(th))
        yaw = math.radians(9.0 + 14.0 * (1.0 - math.cos(4.0 * math.pi * u)))   # 9 to 37 degrees in from ahead
        look = (fwd[0] * math.cos(yaw) + inward[0] * math.sin(yaw), fwd[2] * math.cos(yaw) + inward[2] * math.sin(yaw))
        tgt = (pos[0] + 500.0 * look[0], CAM_H - 36.0, pos[2] + 500.0 * look[1])
        kp.append({"time": round(PERIOD * u, 4), "value": [round(v, 3) for v in pos], "interp": "smooth"})
        kt.append({"time": round(PERIOD * u, 4), "value": [round(v, 3) for v in tgt], "interp": "smooth"})
    s.track("camera/position", kp, loop=PERIOD)
    s.track("camera/target", kt, loop=PERIOD)
    s.camera = {"mode": 1, "position": kp[0]["value"], "target": kt[0]["value"], "fov": 40.0, "orbitSpeed": 0.0}


def build():
    generate_meshes()
    s = kit.Scene(ID, TITLE, DESIGN)
    s.unshadowed_key()          # every material is unlit: the default key's shadow would be pure cost
    s.response = {"sensitivity": 0.5, "transient": 0.55, "sustain": 0.55, "attack": 1.0, "release": 1.1,
                  "floorDb": -44.0, "rangeDb": 42.0}     # mastered music does not saturate the levels
    # nothing is lit and nothing is fogged: the programs paint the light and the air
    s.environment = {
        "intensity": 0.0, "background": hexrgb(HORIZON_COOL), "fogColor": hexrgb(HAZE_COOL), "volumeDensity": 0.0,
        "skyIntensity": 1.0,
        "sky": {"enabled": True, "zenithColor": hexrgb(ZENITH), "horizonColor": hexrgb(HORIZON_COOL),
                "groundColor": hexrgb(HORIZON_COOL), "haze": 0.3, "sunIntensity": 0.0, "intensity": 1.0,
                "background": True, "useKeyLight": False},
    }
    s.program(rock_program())
    s.program(sky_program())
    s.program(water_program())

    # ---- the sky: a dome with a short program (it covers the frame); the sky in the lake: a disc 1 km below the
    # waterline, 30 km across, behind every twin, with the water's program (only where there is water). The band of
    # water nearer the horizon than the disc's edge is the dome's own far-water colour.
    s.proc("dome", {"kind": "sphere", "radius": 1000.0, "segments": 64, "rings": 32},
           material=unlit("#000000", 0.0, program="daSky", double=True),
           transform={"position": [0.0, 0.0, 0.0], "rotation": [0.0, 0.0, 0.0], "scale": [7.0, 7.0, 7.0]})
    s.proc("lakeSky", {"kind": "cylinder", "radius": 1000.0, "height": 1.0, "radialSegments": 64, "caps": True},
           material=unlit("#000000", 0.0, program="daWater"),
           transform={"position": [0.0, -1000.0, 0.0], "rotation": [0.0, 0.0, 0.0], "scale": [30.0, 1.0, 30.0]})

    # ---- AUDIO TOPOGRAPHY: a wave rolling outward from the island (a sine train, 900 m long, at 150 m/s); the routes
    # set how tall it is
    s.nodes.append({"name": "swell", "kind": "field", "field": {
        "kind": "wave", "waveGeometry": "cylindrical", "waveShape": "sine", "amplitude": 1.0, "wavelength": 900.0,
        "waveSpeed": 150.0, "waveWidth": 0.0, "axis": [0.0, 1.0, 0.0], "position": [0.0, 0.0, 0.0],
        "strength": 1.0}})

    # ---- the land: four ranges round the lake, the island, the rocks (each with its twin)
    for name, *_r, band in RANGES:
        landform(s, name, band)
    landform(s, "island")
    landform(s, "rocks")

    # ---- twelve lanterns on the shore, the pitch classes (C at the island's north, round clockwise), and their twins
    for k in range(12):
        a = -2.0 * math.pi * k / 12.0
        x, z = 540.0 * math.sin(a), 540.0 * math.cos(a)
        for twin in (False, True):
            s.proc("lantern%d" % k + ("Twin" if twin else ""), {"kind": "sphere", "radius": 2.0, "segments": 12,
                                                                  "rings": 8},
                   material={"baseColor": [0.0, 0.0, 0.0], "emissiveColor": hexrgb("#ffc890"),
                             "emissiveIntensity": 2.0, "roughness": 1.0, "metallic": 0.0, "unlit": True},
                   transform={"position": [x, -2.6 if twin else 2.6, z], "rotation": [0, 0, 0], "scale": [1, 1, 1]})

    # ---- glints on the water (the highs) and the rings of light where onsets land (drops that splash at y = 0)
    s.particles("glints", capacity=8000, seed=5, shape="disc", position=[0.0, 0.25, 0.0], extent=[520.0, 0.1, 520.0],
                direction=[0.0, 1.0, 0.0], spawnRate=60.0, lifetimeMin=0.12, lifetimeMax=0.4, spread=0.0,
                speedMin=0.0, speedMax=0.0, gravity=[0, 0, 0], drag=0.0, sizeStart=0.9, sizeEnd=0.0,
                colorStart=hexrgb("#fff2e0") + [1.0], colorEnd=hexrgb(HORIZON_WARM) + [0.0], emissive=5.0,
                blend="additive", turbulence=0.0)
    s.particles("drops", capacity=600, seed=9, shape="disc", position=[0.0, 0.6, 0.0], extent=[460.0, 0.1, 460.0],
                direction=[0.0, -1.0, 0.0], spawnRate=0.0, lifetimeMin=2.0, lifetimeMax=2.0, spread=0.0,
                speedMin=8.0, speedMax=8.0, gravity=[0, 0, 0], drag=0.0, sizeStart=2.4, sizeEnd=2.4,
                colorStart=hexrgb("#ffe6d8") + [0.75], colorEnd=hexrgb("#c9b6ff") + [0.0], emissive=2.5,
                blend="additive", turbulence=0.0, collision="splash", collisionHeight=0.0, splashLifetime=2.2,
                splashSize=7.0, ringThickness=0.06)

    # ---- the camera: a low glide round the lake, banking into the turn
    camera_track(s)
    s.track("camera/roll", [{"time": 0.0, "value": -2.5, "interp": "smooth"},
                            {"time": PERIOD * 0.5, "value": -4.0, "interp": "smooth"},
                            {"time": PERIOD, "value": -2.5, "interp": "smooth"}], loop=PERIOD)
    s.params_({"camera/lens/focalLength": 24.0, "post/bloom/intensity": 0.25, "post/bloom/threshold": 1.6,
               "post/bloom/emissionWeight": 1.0, "post/output/vignette": 0.3, "post/output/grain": 0.012,
               "post/tonemap/operator": 4})

    instrument(s)
    s.region("sky", box=[0.0, 0.0, 1.0, 0.42])
    s.region("lake", box=[0.0, 0.5, 1.0, 1.0])
    return s
