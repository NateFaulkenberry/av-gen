def unlit(hexc="#000000", intensity=0.0, program="daRock", double=False):
    m = {"baseColor": [0.0, 0.0, 0.0], "emissiveColor": hexrgb(hexc), "emissiveIntensity": float(intensity),
         "roughness": 1.0, "metallic": 0.0, "unlit": True, "program": program}
    if double:
        m["doubleSided"] = True
    return m


def swell(axis_y=1.0):
    """AUDIO TOPOGRAPHY: the travelling wave field displaces every vertex vertically (a twin's, downward)."""
    return [{"kind": "field", "field": "swell", "amount": 0.0, "axis": [0.0, float(axis_y), 0.0], "space": "world",
             "alongNormal": False}]


def landform(s, name, band="#000000"):
    for twin in (False, True):
        s.proc(name + ("Twin" if twin else ""),
               {"kind": "mesh", "asset": "meshes/da-%s%s.glb" % (name, "-twin" if twin else "")},
               material=unlit(band, 0.0), deformers=swell(-1.0 if twin else 1.0))


LANDFORMS = [r[0] for r in RANGES] + ["island", "rocks"]


def instrument(s):
    """The modulation map (ABSTRACT-PLAN.md section 6)."""
    P = "procedural/%s/"
    # ---- AUDIO TOPOGRAPHY: the level sets how tall the waves rolling out through the mountains are (metres)
    for node in LANDFORMS:
        for suffix in ("", "Twin"):
            s.route(R("level", P % (node + suffix) + "deform/1/amount", 12.0, attackMs=400, decayMs=1800))
    # ---- SPECTRAL DEPTH: each range lights with its own band, near to far (its emission is added to the facets by the
    # program, before the haze)
    for name, *_r, band_col in RANGES:
        for suffix in ("", "Twin"):
            s.route(R(BANDS[name], P % (name + suffix) + "material/emissive", 0.16, attackMs=60, decayMs=700))
    # ---- BASS: the sun's path on the water brightens
    s.route(R("bass", "material/daWater/op/29/constant/constant", 1.2, attackMs=30, decayMs=500))
    # ---- KICK: the low sun flares across every facet that faces it; rings of light land on the water
