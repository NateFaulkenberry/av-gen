def sector(area, count, radius, jitter=(0.0, 0.0, 0.0), seed=1, margin=6.0):
    """A radial distribution over one area's arc of the ring (counter-clockwise from above, like the swim)."""
    a0 = math.radians(AREAS[area][1] + margin)
    a1 = math.radians(AREAS[area][1] + 120.0 - margin)
    # the engine's xz radial puts angle e at (cos e, 0, -sin e); ours puts theta at (sin theta, 0, cos theta), so
    # e = theta - pi/2 (both increase the same way round)
    d = {"kind": "radial", "count": int(count), "radius": float(radius), "plane": "xz", "orientation": "outward",
         "startAngle": a0 - math.pi / 2.0, "endAngle": a1 - math.pi / 2.0}
    v = {"seed": seed, "randomPosition": list(jitter), "randomRotation": [0.0, math.pi, 0.0],
         "randomUniformScale": 0.25}
    return d, v


def at_angle(deg, r, y=0.0):
    th = math.radians(deg)
    return [r * math.sin(th), y, r * math.cos(th)]


def lane_angle(arc_m):
    """Degrees along the swim for a distance along the lane from the lap's start."""
    return math.degrees(THETA0) + math.degrees(arc_m / RC)


