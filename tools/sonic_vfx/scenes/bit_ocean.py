# ================================================================================================ the level's meshes
def polar(x, z):
    r = math.hypot(x, z)
    th = math.atan2(x, z) % (2.0 * math.pi)       # 0 at +z, increasing towards +x (the swim's direction)
    return r, th


def area_of(th):
    return min(2, int(math.degrees(th) // 120.0))


def floor_height(x, z):
    """In blocks: the lane a shallow trough, rising to terraces either side, walls at the ring's edges, the basin
    falling away inside."""
    r, th = polar(x, z)
    d = abs(r - RC)
    n = mx.fbm(x / 26.0, z / 26.0, 3, 3)
    side = mx.smooth(LANE + 4.0, 58.0, d)
    h = 1.0 + (1.0 if n > 0.64 else 0.0) * (1.0 - side) + (2.0 + 2.6 * n) * side   # the lane one block deep
    if r > RC + 48.0:
        h += 5.0 * mx.smooth(RC + 48.0, RC + 70.0, r) * (0.6 + 0.8 * mx.fbm(x / 14.0, z / 14.0, 9, 2))
    if r < RC - 48.0:
        h -= 6.0 * mx.smooth(RC - 48.0, RC - 66.0, r)
    return int(round(h))


def floor_cells(area):
    cells = set()
    n = int((RC + 80.0) / CELL)
    for i in range(-n, n + 1):
        for k in range(-n, n + 1):
            x, z = (i + 0.5) * CELL, (k + 0.5) * CELL
            r, th = polar(x, z)
            if r < RC - 70.0 or r > RC + 78.0 or area_of(th) != area:
                continue
            h = floor_height(x, z)
            for j in range(min(h, 0) - 1, h):
                cells.add((i, j, k))
    return cells


def kelp_cells(seed, height=11):
    """A kelp plant: a stem of blocks that leans a little as it climbs, leaves alternating left and right."""
    cells = set()
    x = 0
    for j in range(height):
        if mx._hash(seed, j, 3) < 0.18:
            x += 1 if mx._hash(seed, j, 4) < 0.5 else -1
        cells.add((x, j, 0))
        if j > 1 and j % 2 == 0:
            side = 1 if (j // 2) % 2 else -1
            cells.add((x + side, j, 0))
            if mx._hash(seed, j, 5) < 0.5:
                cells.add((x + side, j + 1, 0))
    return cells


def coral_cells(seed):
    """Branch coral: a trunk splitting into blocky branches."""
    cells = {(0, 0, 0), (0, 1, 0)}
    tips = [(0, 1, 0)]
    for g in range(3):
        new = []
        for (x, y, z) in tips:
            for b in range(2):
                dx = 1 if mx._hash(seed, g * 7 + b, x + 9) < 0.5 else -1
                dz = 1 if mx._hash(seed, g * 5 + b, z + 4) < 0.5 else -1
                px, py, pz = x, y, z
                for s in range(2):
                    if s == 0:
                        px += dx if b == 0 else 0
                        pz += dz if b == 1 else 0
                    py += 1
                    cells.add((px, py, pz))
                new.append((px, py, pz))
        tips = new
    return cells


def rock_cells(seed, rx=3, ry=2, rz=3):
    cells = set()
    for i in range(-rx, rx + 1):
        for j in range(0, ry + 1):
            for k in range(-rz, rz + 1):
                e = (i / (rx + 0.5)) ** 2 + (j / (ry + 0.6)) ** 2 + (k / (rz + 0.5)) ** 2
                if e < 1.0 - 0.35 * mx._hash(i + 7, j * 13 + k, seed):
                    cells.add((i, j, k))
    return cells


def fish_tris():
    """A geometric fish facing +z: a diamond body and a fin tail."""
    nose, tail = (0.0, 0.0, 0.75), (0.0, 0.0, -0.55)
    top, bot, l, r = (0.0, 0.42, 0.0), (0.0, -0.36, 0.0), (-0.2, 0.0, 0.05), (0.2, 0.0, 0.05)
    body = [(nose, top, r), (nose, r, bot), (nose, bot, l), (nose, l, top),
            (tail, r, top), (tail, bot, r), (tail, l, bot), (tail, top, l)]
    t0, t1, t2 = (0.0, 0.0, -0.5), (0.0, 0.38, -1.05), (0.0, -0.38, -1.05)
    fin = [(t0, t1, t2), (t0, t2, t1)]
    return body + fin


def guide_cells():
    """THE GUIDE, facing +z in cells of GUIDE_CELL: {part: cells} for an orange body, a cream belly, coral fins, white
    eyes, navy pupils and mouth. One solid: the parts are split out of it, so no face is drawn between two of them."""
    body = set()
    span = {}
    for k in range(-6, 10):                                    # tail root to nose
        u = (k + 6) / 15.0
        f = math.sin(math.pi * (0.1 + 0.84 * u)) ** 0.75
        hh, hw = 0.6 + 3.7 * f, 0.5 + 2.7 * f                  # half-height, half-width (cells)
        span[k] = (hh, hw)
        for j in range(-5, 6):
            for i in range(-4, 5):
                if (i / hw) ** 2 + (j / hh) ** 2 <= 1.0:
                    body.add((i, j, k))
    belly = {c for c in body if c[1] < -0.3 * span[c[2]][0]}
    fins = set()
    for k in range(-10, -6):                                   # the tail: a fork, wider as it goes
        d = -6 - k
        for j in range(-d - 1, d + 2):
            if abs(j) >= d - 1:
                fins.add((0, j, k))
    top = {k: max(j for (i, j, kk) in body if kk == k and i == 0) for k in range(-6, 10)}
    for k, h in ((0, 3), (1, 3), (2, 2), (3, 2), (4, 1)):     # the dorsal fin, a swept sail
        for j in range(1, h + 1):
            fins.add((0, top[k] + j, k - (j - 1)))
    for sgn in (-1, 1):                                        # the pectoral fins, little flaps
        for k in (3, 4):
            w = int(span[k][1])
            fins |= {(sgn * (w + 1), -1, k), (sgn * (w + 2), -2, k - 1)}
    eyes, pupils = set(), set()
    for sgn in (-1, 1):                                        # an eye on each flank, looking forward
        k0 = 6
        w = max(i * sgn for (i, j, kk) in body if kk == k0 and j == 1)
        for j in (1, 2):
            for k in (k0, k0 + 1):
                c = (sgn * max(i * sgn for (i, jj, kk) in body if kk == k and jj == j), j, k)
                eyes.add(c)
        pupils.add((sgn * max(i * sgn for (i, jj, kk) in body if kk == k0 + 1 and jj == 1), 1, k0 + 1))
    nose = max(k for (i, j, k) in body)
    mouth = {(i, -1, max(k for (ii, jj, k) in body if ii == i and jj == -1)) for i in (-1, 0, 1)}
    eyes -= pupils
    solid = body | fins
    parts = {"body": body - belly - eyes - pupils - mouth, "belly": belly - mouth, "fins": fins, "eyes": eyes,
             "pupils": pupils | mouth}
    return solid, parts


def tower_cells():
    """The giant coral tower in the basin: a stacked, branching column."""
    cells = set()
    for j in range(0, 26):
        rad = 4 if j < 8 else (3 if j < 16 else 2)
        for i in range(-rad, rad + 1):
            for k in range(-rad, rad + 1):
                if i * i + k * k <= rad * rad + 1 and mx._hash(i + 31, k + j * 7, 5) > 0.08:
                    cells.add((i, j, k))
    for b, (dx, dz, j0) in enumerate(((1, 0, 9), (-1, 1, 13), (0, -1, 17), (1, 1, 20))):
        x, z = 0, 0
        for s in range(9):
            x += dx if s % 2 == 0 else 0
            z += dz if s % 3 == 0 else 0
            cells.add((x * 1 + dx * 3, j0 + s // 2, z + dz * 3))
    return cells


